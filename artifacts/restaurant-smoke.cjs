const { chromium } = require(process.env.TEMP + '/hotel-ui-qa/node_modules/playwright');
const fs = require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const tag=String(Date.now()).slice(-6);
 const table1='A'+tag, table2='B'+tag, dish='Paneer '+tag;
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:3107/login');
 await page.screenshot({path:'artifacts/login-desktop.png',fullPage:true});
 await page.locator('[name=username]').fill('admin'); await page.locator('[name=password]').fill('UiTest-Only-4927');
 await page.getByRole('button',{name:'Sign in',exact:true}).click(); await page.waitForURL('**/dashboard');
 await page.goto('http://localhost:3107/restaurant/tables');
 for(const n of [table1,table2]) {
 await page.getByRole('button',{name:'Add table',exact:true}).click();
 await page.locator('[role=dialog] [name=table_no]').fill(n);
 await page.getByRole('button',{name:'Save table',exact:true}).click();
 await page.locator('[role=dialog]').waitFor({state:'hidden'});
 }
 await page.goto('http://localhost:3107/restaurant/menu');
 await page.getByRole('button',{name:'Add item',exact:true}).click();
 await page.locator('[role=dialog] [name=name]').fill(dish);
 await page.locator('[name=category]').fill('Starters'); await page.locator('[name=price]').fill('240');
 await page.locator('[role=dialog]').getByRole('button',{name:'Add item',exact:true}).click();
 await page.locator('[role=dialog]').waitFor({state:'hidden'});
 await page.goto('http://localhost:3107/restaurant/new?table='+table1);
 await page.getByRole('button',{name:new RegExp(dish)}).click();
 await page.locator('input[placeholder="Note for kitchen (optional)"]').fill('No chilli');
 await page.getByRole('button',{name:/Place order/}).click(); await page.waitForURL(/\/restaurant\/\d+$/);
 const orderUrl=page.url();
 await page.goto('http://localhost:3107/restaurant/tables');
 await page.getByText('Occupied',{exact:true}).waitFor();
 await page.screenshot({path:'artifacts/dining-floor-desktop.png',fullPage:true});
 await page.goto('http://localhost:3107/restaurant/kitchen');
 await page.getByText('No chilli',{exact:true}).last().waitFor();
 await page.screenshot({path:'artifacts/kitchen-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'Start preparing',exact:true}).click();
 await page.getByRole('button',{name:'Mark served',exact:true}).waitFor();
 await page.getByRole('button',{name:'Mark served',exact:true}).click();
 await page.goto(orderUrl);
 page.on('dialog',d=>d.accept());
 await page.locator('select[name=table_no]').selectOption(table2);
 await page.getByRole('button',{name:'Move order',exact:true}).click();
 await page.getByText('Order transferred.',{exact:true}).waitFor();
 await page.locator('[name=discount_percent]').fill('10');
 await page.locator('[name=discount_reason]').fill('QA manager approval');
 await page.getByRole('button',{name:'Apply discount',exact:true}).click();
 await page.getByText('Discount and tax totals updated.',{exact:true}).waitFor();
 await page.getByLabel('Split across two payment methods').check();
 await page.locator('[name=second_amount]').fill('100');
 await page.locator('[name=cash_received]').fill('200');
 await page.getByRole('button',{name:/Receive/}).click();
 await page.getByText('Completed',{exact:true}).first().waitFor();
 await page.goto(orderUrl.replace('/restaurant/','/print/order/'));
 for (const width of ['58','80']) {
 await page.getByLabel('Thermal paper width').selectOption(width);
 await page.emulateMedia({media:'print'});
 const size=await page.locator('.thermal-container').evaluate(el=>el.getBoundingClientRect().width);
 if(Math.abs(size-Number(width)*96/25.4)>1) throw Error('Incorrect thermal width '+size);
 await page.pdf({path:`artifacts/receipt-${width}mm.pdf`,width:`${width}mm`,height:'240mm',printBackground:false,margin:{top:0,bottom:0,left:0,right:0}});
 await page.emulateMedia({media:'screen'});
 }
 await page.setViewportSize({width:390,height:844});
 await page.goto('http://localhost:3107/restaurant/tables');
 await page.screenshot({path:'artifacts/dining-floor-mobile.png',fullPage:true});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 if(overflow) throw Error('Mobile horizontal overflow');
 if(errors.length) throw Error(errors.join('\n'));
 console.log('PASS: login, table creation, menu, POS, kitchen lifecycle, transfer, settlement, 58/80mm print width, mobile layout; no browser errors.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
